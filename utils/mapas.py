#  Codificación numérica:
#  0: Celda libre
#  1: Pared / obstáculo
#  2: Salida de evacuación (S)

CHAR_MAP = {
    ".": TipoCuadricula.CAMINABLE,
    "#": TipoCuadricula.MURO,
    "S": TipoCuadricula.SALIDA,
    "F": TipoCuadricula.FUEGO,
    "A": TipoCuadricula.CAMINABLE,
    "0": TipoCuadricula.CAMINABLE,
    "1": TipoCuadricula.MURO,
}


def parse_map(map_str: str) -> np.ndarray:
    lines = [
        line.strip() for line in map_str.strip().split("\n") if line.strip()
    ]
    rows = []
    for line in lines:
        row = line.split()
        rows.append([CHAR_MAP[char].value for char in row])
    return np.array(rows, dtype=np.int8)


def parse_numeric_map(map_str: str) -> np.ndarray:
    lines = [
        line.strip() for line in map_str.strip().split("\n") if line.strip()
    ]
    rows = []
    for line in lines:
        tokens = line.split()
        if len(tokens) > 50:
            tokens = tokens[:50]
        if len(tokens) < 50:
            raise ValueError(f"Fila con longitud inválida ({len(tokens)}): {line!r}")

        row = []
        for token in tokens:
            if token not in CHAR_MAP:
                raise ValueError(f"Token desconocido en mapa: {token!r}")
            row.append(CHAR_MAP[token].value)
        rows.append(row)

    if not rows:
        raise ValueError("El mapa está vacío")
    return np.array(rows, dtype=np.int8)


